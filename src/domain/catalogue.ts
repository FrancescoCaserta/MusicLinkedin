import type { Genre } from './types';
import { normalise } from './taxonomy';

/**
 * A working catalogue of real repertoire, organised the way musicians think
 * about it: what a given instrument or voice is actually asked to play.
 * It feeds the seed data, the repertoire autocomplete and the query parser.
 * It is deliberately not exhaustive — users can always type any work.
 */

export interface Work {
  composer: string;
  work: string;
  genre: Genre;
  /** Operatic role or solo part, where the pool is voice-specific. */
  part?: string;
}

const g =
  (genre: Genre) =>
  (composer: string, ...works: string[]): Work[] =>
    works.map((work) => ({ composer, work, genre }));

const concerto = g('concerto');
const solo = g('solo');
const chamber = g('chamber');
const orch = g('orchestral');
const sacred = g('sacred');
const song = g('song');
const contemp = g('contemporary');

const role = (composer: string, work: string, part: string): Work => ({ composer, work, genre: 'opera', part });
const part = (composer: string, work: string, p: string): Work => ({ composer, work, genre: 'sacred', part: p });

