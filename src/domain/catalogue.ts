/** Every work in the catalogue, de-duplicated by composer + title. */
export const ALL_WORKS: Work[] = (() => {
  const seen = new Set<string>();
  const out: Work[] = [];
  const pools = [
    ...Object.values(SOLO_REPERTOIRE),
    ORCHESTRAL_WORKS,
    CHAMBER_ORCHESTRA_WORKS,
    OPERA_WORKS,
    SACRED_WORKS,
    BAROQUE_ENSEMBLE_WORKS,
    STRING_CHAMBER_WORKS,
    PIANO_CHAMBER_WORKS,
    WIND_CHAMBER_WORKS,
    BRASS_CHAMBER_WORKS,
    CONTEMPORARY_WORKS,
    CHORAL_WORKS,
    CONTINUO_WORKS,
    SONG_WORKS,
    ...Object.values(VOICE_REPERTOIRE),
  ];
  for (const pool of pools) {
    for (const w of pool) {
      const key = `${w.composer}|${w.work}`;
      if (seen.has(key)) continue;
      seen.add(key);
      out.push({ composer: w.composer, work: w.work, genre: w.genre });
    }
  }
  return out;
})();

export const COMPOSERS: string[] = [...new Set(ALL_WORKS.map((w) => w.composer))].sort((a, b) =>
  a.localeCompare(b),
);

