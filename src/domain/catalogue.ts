export interface ComposerTerm {
  term: string;
  composer: string;
}

/** Normalised search terms for composers, longest first. */
export const COMPOSER_TERMS: ComposerTerm[] = (() => {
  const out = new Map<string, string>();
  for (const c of COMPOSERS) {
    out.set(normalise(c), c);
    // surname without initials: "R. Strauss" → "strauss" (kept only if unambiguous or aliased)
    const bare = normalise(c.replace(/^([A-Z]\.\s?)+/, ''));
    if (!out.has(bare)) out.set(bare, c);
  }
  for (const [alias, c] of Object.entries(COMPOSER_ALIASES)) out.set(alias, c);
  return [...out.entries()]
    .map(([term, composer]) => ({ term, composer }))
    .sort((a, b) => b.term.length - a.term.length);
})();

/** Autocomplete for the repertoire field: composers first, then works. */
export function suggestRepertoire(text: string, limit = 8): { label: string; composer: string; work?: string }[] {
  const q = normalise(text);
  if (q.length < 2) return [];
  const out: { label: string; composer: string; work?: string }[] = [];
  for (const c of COMPOSERS) {
    if (normalise(c).includes(q)) out.push({ label: c, composer: c });
    if (out.length >= 3) break;
  }
  const words = q.split(' ');
  for (const w of ALL_WORKS) {
    const hay = normalise(`${w.composer} ${w.work}`);
    if (words.every((x) => hay.includes(x))) {
      out.push({ label: `${w.composer} — ${w.work}`, composer: w.composer, work: w.work });
      if (out.length >= limit) break;
    }
  }
  return out.slice(0, limit);
}

export function worksByComposer(composer: string): Work[] {
  return ALL_WORKS.filter((w) => w.composer === composer);
}
