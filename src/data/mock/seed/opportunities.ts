import type { Fee, ISODate, OpportunityDateKind, OpportunityType, ProgrammeItem, TravelCover } from '../../../domain/types';

/**
 * Hand-written opportunities. Dates are expressed relative to the day the
 * demo is seeded so the board always looks current.
 */

export interface OpportunitySeed {
  id: string;
  type: OpportunityType;
  title: string;
  /** Organisation id — posted by its admin … */
  org?: string;
  /** … or a roster musician posting in their own name. */
  by?: string;
  instruments: string[];
  role?: string;
  city: string;
  venue?: string;
  dates: [ISODate, OpportunityDateKind, string?, string?][];
  fee: Fee;
  travel: TravelCover;
  travelNote?: string;
  dress?: string;
  pitch?: number;
  rep: [string, string][];
  text: string;
  deadline?: ISODate;
  urgent?: boolean;
  /** Days ago it was posted. */
  posted: number;
  /** Hours ago, for urgent postings. */
  postedHours?: number;
}

export interface DateTools {
  /** Anchor + n days. */
  day: (n: number) => ISODate;
  /** First given weekday (0 = Mon … 6 = Sun) on or after anchor + n days. */
  on: (weekday: number, n: number) => ISODate;
  /** The "14 March" of the demo sentence. */
  demo: ISODate;
  /** demo + n days */
  demoPlus: (n: number) => ISODate;
}

export const rep = (list: [string, string][]): ProgrammeItem[] => list.map(([composer, work]) => ({ composer, work }));

